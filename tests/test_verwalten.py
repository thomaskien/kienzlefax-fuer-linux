    def test_inventory_reads_frozen_queued_restart_without_waiting(self):
        host = v.Host()
        status = ('LoadState=loaded\nUnitFileState=enabled\nFreezerState=frozen\n'
                  'ActiveState=activating\nSubState=auto-restart-queued\n', 0)
        with patch.object(host, 'run', return_value=status) as run, patch.object(v.time, 'sleep') as sleep:
            self.assertEqual(host.service('scan-ocr-fax.service'),
                             {'active': False, 'enabled': 'enabled', 'frozen': True})
        self.assertEqual(run.call_count, 1)
        self.assertEqual(run.call_args.args[:2], ('systemctl', 'show'))
        sleep.assert_not_called()

    def test_atomic_write_preserves_permissions_and_never_follows_symlink(self):
        import os
        host = v.Host()
        with tempfile.TemporaryDirectory() as temp:
            # Resolve macOS /var -> /private/var before exercising the Linux path guard.
            root = Path(temp).resolve()
            path = root / 'config'
            snap = v.text_snapshot('secret', mode=0o600)
            snap.update(uid=os.geteuid(), gid=os.getegid())
            host.write(str(path), snap)
            self.assertEqual(host.snapshot(str(path)), snap)
            target = root / 'alias'
            target.symlink_to(path)
            with self.assertRaises(v.Error):
                host.write(str(target), snap)
            self.assertEqual(path.read_text(), 'secret')

    def test_missing_service_is_not_a_fatal_inventory_error(self):
        host = v.Host()
        with patch.object(host, 'run', return_value=('LoadState=not-found\nActiveState=inactive\n', 4)):
            self.assertIsNone(host.service('nonexistent.service'))

    def test_printer_parse_printing_disabled_and_rejecting(self):
        host = v.Host()
