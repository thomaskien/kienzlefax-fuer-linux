def generated_fax_dialplan():
    """Include the footer appended *after* the installer's main heredoc."""
    source = (SCRIPT.parent / 'installer-modular/extensions.sh').read_text()
    text = re.findall(r'cat >"\$EXT" <<\'EOF\'\n(.*?)\nEOF', source, re.S)[-1]
    footer = re.search(r"^printf '\\n(#tryinclude [^']+)\\n' >>\"\$EXT\"$", source, re.M)
    if footer is None:
        raise AssertionError('Installer footer changed; update the complete dialplan fixture.')
    text = text.replace('__KFX_FAX_DID__', '12345')
    text = text.replace('__KFX_PHONE_ROUTE__', 'exten => 67890,1,Goto(kfx-phone-in,s,1)')
    return text + '\n\n' + footer.group(1) + '\n'


class FakeHost(v.Host):
    def __init__(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.files = {}
        self.units = {name: {'active': True, 'enabled': 'enabled', 'frozen': False}
                      for name in (*v.SERVICES.values(), 'asterisk.service', 'smbd.service', 'apache2.service')}
        self.flags = {'fax1': {'enabled': True, 'accepting': True},
                      'fax2': {'enabled': False, 'accepting': True}}
        self.commands = []
        self.writes = []
        self.calls = False
        self.busy = set()
        self.connected = set()
        self.jobs = set()
        self.fail_write = None
        self.queue = 0
        self.put(v.EXT, EXT, 0o640)
        self.put(v.PJSIP, PJSIP, 0o640)
        self.put(v.PHONE_PJSIP, PHONE, 0o640)
        self.put(v.PHONE_EXT, PHONE_EXT, 0o640)
        self.put(v.SMB, SMB)
        self.put(v.WEB, WEB_PHP)
        self.path('/var/www/html/kienzlefax.php').parent.mkdir(parents=True)
        self.path('/var/www/html/kienzlefax.php').touch()

    def close(self):
        self.temp.cleanup()

    def path(self, path):
        return self.root / path.lstrip('/')

    def put(self, path, text, mode=0o644):
        self.files[path] = v.text_snapshot(text, mode=mode)

    def snapshot(self, path):
        return copy.deepcopy(self.files.get(path))

    def write(self, path, snapshot):
        if self.fail_write == path:
            self.fail_write = None
            raise v.Error('simulierter Schreibfehler')
        self.writes.append(path)
        if snapshot is None:
            self.files.pop(path, None)
        else:
            self.files[path] = copy.deepcopy(snapshot)

    def service(self, unit):
        return copy.deepcopy(self.units.get(unit))

    def run(self, *args, **kwargs):
        self.commands.append(args)
        if args[0] == 'cupsreject':
            self.flags[args[1]]['accepting'] = False
        return '', 0

    def ast(self, command):
        raise AssertionError('Live-Dienststeuerung ist im Neustart-Ablauf nicht erlaubt.')

    def idle_calls(self):
        v.require(not self.calls, 'Telefonat oder Fax aktiv.')

    def idle_processing(self, key):
        v.require(key not in self.busy, 'Verarbeitung nicht leer: ' + key)

    def can_freeze(self, unit):
        pass

    def idle_share(self, name):
        v.require(name not in self.connected, 'Verbindung offen: ' + name)

    def idle_printer(self, name):
        v.require(name not in self.jobs, 'Druckauftraege vorhanden: ' + name)

    def freeze(self, unit):
        raise AssertionError('Live-Dienststeuerung ist im Neustart-Ablauf nicht erlaubt.')

    def thaw(self, unit):
        raise AssertionError('Live-Dienststeuerung ist im Neustart-Ablauf nicht erlaubt.')

    def service_active(self, unit, active):
        raise AssertionError('Live-Dienststeuerung ist im Neustart-Ablauf nicht erlaubt.')

    def printers(self):
        return list(self.flags)

    def printer(self, name):
        return copy.deepcopy(self.flags[name])

    def printer_set(self, name, flags):
        self.flags[name] = copy.deepcopy(flags)

    def validate_samba(self, text):
        pass

    def reload(self, paths, disabled, verify=True):
        raise AssertionError('Live-Dienststeuerung ist im Neustart-Ablauf nicht erlaubt.')

    def queue_count(self):
        return self.queue


class ManagementTests(unittest.TestCase):
    def setUp(self):
        self.host = FakeHost()
        self.addCleanup(self.host.close)
        self.manager = v.Manager(self.host)

    def apply(self, disabled):
        plan = self.manager.plan(set(disabled))
        self.manager.apply(plan)
        return plan

    def test_inventory_individual_components(self):
        found = self.manager.inventory()
        self.assertIn('scan_ocr', found)
        self.assertIn('fax_ocr', found)
        self.assertIn('share:scan-eingang', found)
        self.assertIn('share:pdf-zu-fax2', found)
        self.assertIn('printer:fax2', found)
        self.assertNotIn('share:unrelated', found)

    def test_single_share_restores_exact_file_and_permissions(self):
        before = self.host.snapshot(v.SMB)
        self.apply({'share:scan-eingang'})
        content = v.snapshot_text(self.host.snapshot(v.SMB))
        self.assertIn('[scan-eingang]\n   available = no\n', content)
        self.assertIn('[unrelated]\npath = /srv/other\nguest ok = no\n', content)
        self.apply(set())
        self.assertEqual(self.host.snapshot(v.SMB), before)

    def test_shared_file_reenable_one_keeps_other_paused(self):
        self.apply({'share:scan-eingang', 'share:pdf-zu-fax2'})
        self.apply({'share:pdf-zu-fax2'})
        content = v.snapshot_text(self.host.snapshot(v.SMB))
        self.assertIn('[scan-eingang]\npath = /srv/scan/ocr\navailable = yes', content)
        self.assertIn('[pdf-zu-fax2]\n   available = no', content)

    def test_undo_last_only_returns_previous_combination(self):
        self.apply({'share:scan-eingang'})
        second = self.apply({'share:scan-eingang', 'web'})
        self.manager.rollback(second)
        self.assertEqual(self.manager.state['disabled'], ['share:scan-eingang'])
        self.assertEqual(v.snapshot_text(self.host.snapshot(v.WEB)), WEB_PHP)
        self.assertIn('available = no', v.snapshot_text(self.host.snapshot(v.SMB)))

    def test_service_roundtrip_restores_original_runtime_without_enable(self):
        self.host.units['scan-ocr.service']['active'] = False
        self.host.units['scan-ocr.service']['enabled'] = 'disabled'
        self.apply({'scan_ocr'})
        self.assertIn('ConditionPathExists=!', v.snapshot_text(self.host.snapshot(v.dropin('scan-ocr.service'))))
        self.apply(set())
        self.assertFalse(self.host.units['scan-ocr.service']['active'])
        self.assertEqual(self.host.units['scan-ocr.service']['enabled'], 'disabled')
        self.assertIsNone(self.host.snapshot(v.dropin('scan-ocr.service')))

    def test_active_service_roundtrip_only_changes_boot_configuration(self):
        original = copy.deepcopy(self.host.units)
        self.apply({'scan_ocr'})
        self.assertIsNotNone(self.host.snapshot(v.dropin('scan-ocr.service')))
        self.assertEqual(self.host.units, original)
        self.apply(set())
        self.assertIsNone(self.host.snapshot(v.dropin('scan-ocr.service')))
        self.assertEqual(self.host.units, original)

    def test_active_work_does_not_block_boot_configuration(self):
        self.host.busy.add('scan_ocr')
        self.host.calls = True
        self.host.connected.add('scan-eingang')
        original = copy.deepcopy(self.host.units)
        self.apply({'scan_ocr', 'fax_receive', 'share:scan-eingang'})
        self.assertEqual(self.host.units, original)
        self.assertIsNotNone(self.host.snapshot(v.dropin('scan-ocr.service')))

    def test_apply_and_restore_never_control_running_services(self):
        original = copy.deepcopy(self.host.units)
        desired = {'fax_send', 'fax_receive', 'fax_ocr', 'phone', 'scan_ocr', 'web', 'share:scan-eingang'}
        with patch.object(self.host, 'freeze', side_effect=AssertionError('no freeze')), \
                patch.object(self.host, 'thaw', side_effect=AssertionError('no thaw')), \
                patch.object(self.host, 'service_active', side_effect=AssertionError('no start/stop')), \
                patch.object(self.host, 'reload', side_effect=AssertionError('no reload')), \
                patch.object(self.host, 'ast', side_effect=AssertionError('no Asterisk CLI')):
            plan = self.apply(desired)
            self.manager.rollback(plan)
        self.assertEqual(self.host.units, original)
        self.assertFalse(any(cmd[0] in ('systemctl', 'asterisk', 'smbcontrol', 'smbclient') for cmd in self.host.commands))

    def test_paused_scanner_can_resume_with_new_input(self):
        self.apply({'scan_ocr'})
        self.host.busy.add('scan_ocr')
        self.apply(set())
        self.assertTrue(self.host.units['scan-ocr.service']['active'])

    def test_restore_reactivation_does_not_stop_busy_scanner(self):
        self.apply({'scan_ocr'})
        plan = self.apply(set())
        self.host.busy.add('scan_ocr')
        self.manager.rollback(plan)
        self.assertTrue(self.host.units['scan-ocr.service']['active'])
        self.assertIsNotNone(self.host.snapshot(v.dropin('scan-ocr.service')))

    def test_legacy_pending_restore_ignores_frozen_restart_and_stopped_worker(self):
        plan = self.manager.plan({'fax_send', 'fax_receive', 'fax_ocr', 'web', 'share:scan-eingang'})
        plan['before_state']['version'] = '0.1.4'
        self.manager.save(v.PENDING, plan)
        for path, value in plan['after_files'].items():
            self.host.write(path, value)
        self.host.units['scan-ocr-fax.service'].update(active=False, frozen=True)
        self.host.units['kienzlefax-worker.service'].update(active=False)
        original_runtime = copy.deepcopy(self.host.units)
        with patch.object(self.host, 'service', side_effect=AssertionError('no runtime status required')):
            self.manager.rollback(plan, pending=True)
        self.assertEqual(self.host.units, original_runtime)
        for path, value in plan['before_files'].items():
            self.assertEqual(self.host.snapshot(path), value)
        self.assertIsNone(self.host.snapshot(v.PENDING))
        self.assertEqual(self.manager.load(v.LAST)['status'], 'restored')

    def test_recovery_after_interrupted_restore(self):
        plan = self.apply({'share:scan-eingang', 'web'})
        self.host.fail_write = v.WEB
        with self.assertRaises(v.Error):
            self.manager.rollback(plan)
        pending = self.manager.load(v.PENDING)
        self.assertEqual(pending['status'], 'restoring')
        self.manager.rollback(pending, pending=True)
        self.assertEqual(v.snapshot_text(self.host.snapshot(v.SMB)), SMB)
        self.assertEqual(v.snapshot_text(self.host.snapshot(v.WEB)), WEB_PHP)

